import cv2
import numpy as np

# ==========================================
# 1. 내부 파라미터 (K) 및 왜곡 계수
# ==========================================
camera_matrix = np.array([
    [484.45878, 0.0, 291.5055],
    [0.0, 482.5031, 222.66382],
    [0.0, 0.0, 1.0]
], dtype=np.float32)

dist_coeffs = np.array([
    [0.162875, -0.287212, 0.000692, -0.000678, 0.000000]
], dtype=np.float32)

# ==========================================
# 2. 3D 월드 좌표 (단위: m)
# 순서: [X(좌우), Y(전방), Z(바닥=0)]
# ==========================================
object_points = np.array([
    [ 0.75, 1.35, 0.0], # 1번: 왼쪽 아래
    [-0.75, 1.43, 0.0], # 2번: 오른쪽 아래
    [-0.75, 4.43, 0.0], # 3번: 오른쪽 위
    [ 0.75, 4.36, 0.0]  # 4번: 왼쪽 위
], dtype=np.float32)

# ==========================================
# 3. 2D 이미지 좌표 (픽셀)
# ==========================================
image_points = np.array([
    [89, 399],  # 1번 (왼쪽 아래)
    [518, 389], # 2번 (오른쪽 아래)
    [387, 151], # 3번 (오른쪽 위)
    [214, 153]  # 4번 (왼쪽 위)
], dtype=np.float32)

# ==========================================
# 🚀 4. solvePnP 실행 및 카메라 실제 위치 계산
# ==========================================
success, rvec, tvec = cv2.solvePnP(object_points, image_points, camera_matrix, dist_coeffs)

if success:
    # 회전 벡터를 3x3 회전 행렬로 변환
    rmat, _ = cv2.Rodrigues(rvec)
    
    # [핵심 수정] 카메라의 진짜 월드 좌표(현실 위치) 계산 수식: C = -R^T * t
    camera_position = -np.matrix(rmat).T * np.matrix(tvec)

    print("✅ 외부 파라미터 계산 완벽하게 성공!")
    print("-" * 40)
    print("[ 카메라의 실제 설치 위치 (World 좌표계 기준) ]")
    print(f"좌우 (X) : {camera_position[0, 0]:.3f} m (0에 가까울수록 차량 정중앙)")
    print(f"전후 (Y) : {camera_position[1, 0]:.3f} m (기준점으로부터의 앞뒤 거리)")
    print(f"높이 (Z) : {camera_position[2, 0]:.3f} m (★실제 측정한 1.31m와 일치★)")
    print("-" * 40)
    
    print("\n[ 추출된 파라미터 (다음 BEV 노드에 들어갈 핵심 재료) ]")
    print("1. 평행이동 벡터 (tvec):")
    print(tvec.flatten())
    print("\n2. 회전 행렬 (rmat):")
    print(rmat)
else:
    print("❌ 계산 실패. 좌표를 다시 확인해주세요.")